/**
 * `npm run dev:local`: the whole app on this machine with one command, for looking at it.
 * No Docker, no Google OAuth, no real email, never the real (Supabase) database.
 *
 *   1. Postgres 17 (scoop's initdb/pg_ctl, found like e2e/pg.ts does) with its data in
 *      web/.pglocal/ on 127.0.0.1:54330, database pantherwatch_local. The cluster is created on
 *      the first run and reused after that; delete web/.pglocal to start over.
 *   2. `npm run db:migrate` (idempotent), the grade backfill from data/grade-csv when
 *      `grade_terms` is empty, and scripts/seed-local.ts when the owner's user row is missing.
 *      When `syllabi` is empty, the syllabi cron runs once (POST /api/cron/syllabi?sync=1)
 *      as soon as next dev answers: GSU's public term files, every registrable term.
 *   3. A fake Resend on 127.0.0.1:3461 (scripts/fake-resend.ts) that logs every email the app
 *      sends. GoSolar is the REAL one.
 *   4. `next dev --port 3000` with a local env: values from web/.env.local, generated
 *      JWT_SECRET / CRON_SECRET / E2E_TEST_SECRET (written to .env.local once, never printed
 *      here, except E2E_TEST_SECRET inside the sign-in links), dummy Google credentials unless
 *      real ones are in .env.local, and forced local DATABASE_URL / RESEND_* / APP_URL /
 *      ADMIN_EMAILS.
 *
 * Prints one-click sign-in links (GET /api/test/login, see src/app/api/test/login/route.ts).
 * Ctrl+C stops next, the fake Resend and Postgres.
 */
import { spawn, spawnSync, type ChildProcess, type SpawnSyncOptions } from "node:child_process";
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "pg";
import { findBin } from "../e2e/pg";
import { startFakeResend, type FakeResend } from "./fake-resend";
import { OWNER_EMAIL, OWNER_NAME, assertLocalDatabaseUrl, seedLocal } from "./seed-local";

const WEB_DIR = fileURLToPath(new URL("..", import.meta.url));
const IS_WINDOWS = process.platform === "win32";

const APP_PORT = 3000;
const RESEND_PORT = 3461;
const PG_PORT = 54330;
const PG_USER = "postgres";
const PG_DB = "pantherwatch_local";
const PG_DIR = path.join(WEB_DIR, ".pglocal");
const PG_DATA = path.join(PG_DIR, "data");
const PG_LOG = path.join(PG_DIR, "postgres.log");
const ENV_FILE = path.join(WEB_DIR, ".env.local");

const APP_URL = `http://localhost:${APP_PORT}`;
const DATABASE_URL = `postgres://${PG_USER}@127.0.0.1:${PG_PORT}/${PG_DB}?sslmode=disable`;
const SECOND_MEMBER = { email: "student@local.test", name: "Student" };
const GENERATED_SECRETS = ["JWT_SECRET", "CRON_SECRET", "E2E_TEST_SECRET"] as const;

const say = (line: string) => console.log(`[dev:local] ${line}`);

// ------------------------------------------------------------------------------ env

/** Minimal dotenv reader: KEY=VALUE lines, `#` comments, optional surrounding quotes. */
function readEnvFile(file: string): Record<string, string> {
  if (!existsSync(file)) return {};
  const values: Record<string, string> = {};
  for (const raw of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const match = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2];
    const quote = value[0];
    if ((quote === '"' || quote === "'") && value.length >= 2 && value.endsWith(quote)) value = value.slice(1, -1);
    else value = value.replace(/\s+#.*$/, "");
    values[match[1]] = value;
  }
  return values;
}

/** Generates the secrets .env.local lacks and appends them to it (values are never printed). */
function ensureSecrets(fileEnv: Record<string, string>): void {
  const missing = GENERATED_SECRETS.filter((key) => (fileEnv[key] ?? "").length < 32);
  if (missing.length === 0) return;
  const lines = missing.map((key) => {
    fileEnv[key] = randomBytes(32).toString("hex");
    return `${key}=${fileEnv[key]}`;
  });
  const existing = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, "utf8") : "";
  const prefix = existing && !existing.endsWith("\n") ? "\n" : "";
  appendFileSync(
    ENV_FILE,
    `${prefix}# Generated by \`npm run dev:local\` (local only; never use these anywhere else)\n${lines.join("\n")}\n`,
  );
  say(`generated ${missing.join(", ")} into web/.env.local`);
}

function buildAppEnv(fileEnv: Record<string, string>): NodeJS.ProcessEnv {
  if (fileEnv.GOSOLAR_BASE_URL) {
    // Next would load it from .env.local even if it is removed from the child's env.
    throw new Error("web/.env.local sets GOSOLAR_BASE_URL, but dev:local uses the real GoSolar. Remove that line.");
  }
  const env: NodeJS.ProcessEnv = { ...fileEnv, ...process.env };
  // .env.local wins over the shell for the secrets it holds (they were generated for it).
  for (const key of GENERATED_SECRETS) env[key] = fileEnv[key];
  delete env.GOSOLAR_BASE_URL;
  Reflect.deleteProperty(env, "NODE_ENV"); // next dev sets "development"; a stray "production" would disable the sign-in links
  if (env.VERCEL_ENV === "production") delete env.VERCEL_ENV;

  const admins = new Set(
    (env.ADMIN_EMAILS ?? "")
      .split(",")
      .map((email) => email.trim().toLowerCase())
      .filter(Boolean),
  );
  admins.add(OWNER_EMAIL);

  return {
    ...env,
    GOOGLE_CLIENT_ID: fileEnv.GOOGLE_CLIENT_ID || "local-dummy-client-id.apps.googleusercontent.com",
    GOOGLE_CLIENT_SECRET: fileEnv.GOOGLE_CLIENT_SECRET || "local-dummy-client-secret",
    // Forced: the local cluster, the fake Resend, this origin. Never the real database or Resend.
    DATABASE_URL,
    DATABASE_CA_CERT: "",
    APP_URL,
    RESEND_API_KEY: "re_local",
    RESEND_BASE_URL: `http://127.0.0.1:${RESEND_PORT}/resend`,
    ADMIN_EMAILS: [...admins].join(","),
    NEXT_TELEMETRY_DISABLED: "1",
  };
}

// ------------------------------------------------------------------------------ Postgres

function run(file: string, args: string[], options: SpawnSyncOptions = {}): number {
  const result = spawnSync(file, args, { stdio: "inherit", windowsHide: true, ...options });
  if (result.error) throw result.error;
  return result.status ?? 1;
}

function mustRun(file: string, args: string[], options: SpawnSyncOptions = {}): void {
  const status = run(file, args, options);
  if (status !== 0) throw new Error(`${path.basename(file)} ${args.join(" ")} exited with ${status}`);
}

/** `pg_ctl status`: 0 running, 3 not running, 4 no data directory. */
function pgStatus(): number {
  return run(findBin("pg_ctl"), ["-D", PG_DATA, "status"], { stdio: "ignore" });
}

async function startPostgres(): Promise<void> {
  if (!existsSync(path.join(PG_DATA, "PG_VERSION"))) {
    say(`creating a Postgres cluster in ${PG_DATA} (first run)`);
    rmSync(PG_DATA, { recursive: true, force: true });
    mkdirSync(PG_DIR, { recursive: true });
    mustRun(findBin("initdb"), ["-D", PG_DATA, "-U", PG_USER, "--auth=trust", "-E", "UTF8", "--no-locale"], {
      stdio: "ignore",
    });
  }

  if (pgStatus() === 0) {
    say("Postgres is already running on web/.pglocal (left over from an earlier run); reusing it");
  } else {
    say(`starting Postgres on 127.0.0.1:${PG_PORT} (log: ${PG_LOG})`);
    const options = [`-p ${PG_PORT}`, "-c listen_addresses=127.0.0.1", "-c max_connections=50"].join(" ");
    // stdio "ignore": the postmaster inherits stdio handles, and with pipes spawnSync would wait
    // for the server to exit (see e2e/pg.ts).
    const status = run(findBin("pg_ctl"), ["-D", PG_DATA, "-l", PG_LOG, "-o", options, "-w", "-t", "60", "start"], {
      stdio: "ignore",
    });
    if (status !== 0) throw new Error(`pg_ctl start failed (exit ${status}). Is port ${PG_PORT} taken? See ${PG_LOG}`);
  }

  const admin = new Client({ host: "127.0.0.1", port: PG_PORT, user: PG_USER, database: "postgres" });
  await admin.connect();
  try {
    const { rowCount } = await admin.query("SELECT 1 FROM pg_database WHERE datname = $1", [PG_DB]);
    if (!rowCount) await admin.query(`CREATE DATABASE ${PG_DB}`);
  } finally {
    await admin.end();
  }
}

function stopPostgres(): void {
  if (pgStatus() !== 0) {
    say("Postgres stopped");
    return;
  }
  const status = run(findBin("pg_ctl"), ["-D", PG_DATA, "-m", "fast", "-w", "-t", "30", "stop"], { stdio: "ignore" });
  say(status === 0 || pgStatus() !== 0 ? "Postgres stopped" : `pg_ctl stop exited with ${status}`);
}

async function queryLocal<T>(text: string, values: unknown[] = []): Promise<T[]> {
  const client = new Client({ host: "127.0.0.1", port: PG_PORT, user: PG_USER, database: PG_DB });
  await client.connect();
  try {
    return (await client.query(text, values)).rows as T[];
  } finally {
    await client.end();
  }
}

// ------------------------------------------------------------------------------ setup steps

/** Env for the setup subprocesses: the shell's, plus ONLY the local database. */
const setupEnv = (): NodeJS.ProcessEnv => ({ ...process.env, DATABASE_URL, DATABASE_CA_CERT: "" });

/** Returns whether `syllabi` is empty (synced once next dev is up; see syncSyllabi). */
async function prepareDatabase(): Promise<{ syllabiEmpty: boolean }> {
  say("applying migrations (npm run db:migrate)");
  mustRun(IS_WINDOWS ? "npm.cmd" : "npm", ["run", "--silent", "db:migrate"], {
    cwd: WEB_DIR,
    env: setupEnv(),
    shell: IS_WINDOWS,
  });

  const [{ n }] = await queryLocal<{ n: number }>("SELECT count(*)::int AS n FROM grade_terms");
  if (n === 0) {
    say("loading the grade history from data/grade-csv (first run only)");
    mustRun(process.execPath, [path.join(WEB_DIR, "node_modules", "tsx", "dist", "cli.mjs"), "scripts/backfill-grades.ts"], {
      cwd: WEB_DIR,
      env: setupEnv(),
    });
  }

  const owner = await queryLocal("SELECT 1 FROM users WHERE google_sub = $1 OR lower(email) = $2", [
    `local:${OWNER_EMAIL}`,
    OWNER_EMAIL,
  ]);
  if (owner.length === 0) {
    say(`seeding ${OWNER_EMAIL}: watches, schedule and an announcement (scripts/seed-local.ts)`);
    try {
      await seedLocal(DATABASE_URL, (line) => say(line));
    } catch (error) {
      say(`seeding failed (${error instanceof Error ? error.message : String(error)}); continuing without it.`);
      say("It is retried on the next start, or run `npm run seed:local` yourself.");
    }
  }

  const [syllabiRows] = await queryLocal<{ n: number }>("SELECT count(*)::int AS n FROM syllabi");
  return { syllabiEmpty: syllabiRows.n === 0 };
}

/**
 * Runs the syllabi cron through the app (it needs the GoSolar term list and `@/db`, which only
 * load inside Next). Non-fatal: the Syllabus tab is just empty until it succeeds, and it is
 * retried on the next start while the table stays empty.
 */
async function syncSyllabi(cronSecret: string): Promise<void> {
  say("syncing syllabi from GSU's public term files (first run only)");
  try {
    const response = await fetch(`${APP_URL}/api/cron/syllabi?sync=1`, {
      method: "POST",
      headers: { Authorization: `Bearer ${cronSecret}` },
      signal: AbortSignal.timeout(300_000),
    });
    const body = (await response.json().catch(() => ({}))) as {
      terms?: { term: string; upserted: number }[];
      errors?: string[];
      error?: string;
    };
    if (!response.ok) throw new Error(body.error ?? `HTTP ${response.status}`);
    for (const { term, upserted } of body.terms ?? []) say(`  ${term}: ${upserted} syllabi`);
    for (const error of body.errors ?? []) say(`  failed ${error}`);
  } catch (error) {
    say(`syllabi sync failed (${error instanceof Error ? error.message : String(error)}); continuing without it.`);
    say("It is retried on the next start.");
  }
}

/** `next dev` reloads in a loop on a stale .next/dev (docs/runbooks/local-dev.md), so clear it. */
function clearNextDevCache(): void {
  const dir = path.join(WEB_DIR, ".next", "dev");
  const lock = path.join(dir, "lock");
  if (existsSync(lock)) {
    let info: { pid?: number; appUrl?: string } = {};
    let alive = false;
    try {
      info = JSON.parse(readFileSync(lock, "utf8")) as typeof info;
      if (info.pid) {
        process.kill(info.pid, 0); // throws when that process is gone (stale lock)
        alive = true;
      }
    } catch {
      // stale or unreadable lock
    }
    if (alive) throw new Error(`another \`next dev\` (pid ${info.pid}, ${info.appUrl}) is running in web/. Stop it first.`);
  }
  rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
}

async function waitForApp(next: ChildProcess, timeoutMs: number): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (next.exitCode !== null) throw new Error(`next dev exited with ${next.exitCode}`);
    try {
      const response = await fetch(`${APP_URL}/api/test/health`, { signal: AbortSignal.timeout(60_000) });
      if (response.ok) return;
    } catch {
      // not listening yet
    }
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  throw new Error(`next dev did not answer ${APP_URL}/api/test/health within ${timeoutMs / 1000}s`);
}

function loginLink(secret: string, email: string, name: string): string {
  return `${APP_URL}/api/test/login?secret=${encodeURIComponent(secret)}&email=${email}&name=${encodeURIComponent(name)}`;
}

function printBanner(secret: string): void {
  const rule = "=".repeat(78);
  console.log(
    [
      "",
      rule,
      "  PantherWatch is running locally",
      "",
      `  App:              ${APP_URL}`,
      `  Sign in (admin):  ${loginLink(secret, OWNER_EMAIL, OWNER_NAME)}`,
      `  Sign in (member): ${loginLink(secret, SECOND_MEMBER.email, SECOND_MEMBER.name)}`,
      `  Sent emails:      http://127.0.0.1:${RESEND_PORT}/   (fake Resend: nothing is really mailed)`,
      `  Database:         ${DATABASE_URL}`,
      "                    data in web/.pglocal (delete that folder to start over)",
      "",
      "  GoSolar is the real one. Press Ctrl+C to stop everything.",
      rule,
      "",
    ].join("\n"),
  );
}

// ------------------------------------------------------------------------------ main

async function main(): Promise<void> {
  assertLocalDatabaseUrl(DATABASE_URL);
  const fileEnv = readEnvFile(ENV_FILE);
  ensureSecrets(fileEnv);
  const appEnv = buildAppEnv(fileEnv);

  let next: ChildProcess | null = null;
  let resend: FakeResend | null = null;
  let pgTouched = false;
  let stopping = false;

  const shutdown = async (reason: string, code = 0) => {
    if (stopping) return;
    stopping = true;
    say(`stopping (${reason})...`);
    const child = next;
    if (child && child.exitCode === null && child.pid) {
      const exited = new Promise<void>((resolve) => child.once("exit", () => resolve()));
      const wait = (ms: number) => Promise.race([exited, new Promise((resolve) => setTimeout(resolve, ms))]);
      if (IS_WINDOWS) {
        // A console Ctrl+C reaches next too; give it a moment, then kill the whole tree.
        await wait(3000);
        if (child.exitCode === null) spawnSync("taskkill", ["/PID", String(child.pid), "/T", "/F"], { stdio: "ignore" });
      } else {
        child.kill("SIGINT");
        await wait(10_000);
        if (child.exitCode === null) child.kill("SIGKILL");
      }
      await wait(5000);
      say("next dev stopped");
    }
    if (resend) {
      await resend.close();
      say("fake Resend stopped");
    }
    if (pgTouched) stopPostgres();
    process.exit(code);
  };
  for (const signal of ["SIGINT", "SIGTERM", "SIGHUP", "SIGBREAK"] as const) {
    process.on(signal, () => void shutdown(signal));
  }

  try {
    clearNextDevCache();
    pgTouched = true;
    await startPostgres();
    const { syllabiEmpty } = await prepareDatabase();

    resend = await startFakeResend(RESEND_PORT, (email) =>
      say(`EMAIL to ${email.to.join(", ")}: "${email.subject}"  (http://127.0.0.1:${RESEND_PORT}/emails/${email.id})`),
    );
    say(`fake Resend listening on ${resend.url}`);

    say(`starting next dev on ${APP_URL}`);
    const nextBin = path.join(WEB_DIR, "node_modules", "next", "dist", "bin", "next");
    next = spawn(process.execPath, [nextBin, "dev", "--port", String(APP_PORT)], {
      cwd: WEB_DIR,
      env: appEnv,
      stdio: "inherit",
    });
    next.once("exit", (code) => void shutdown(`next dev exited with ${code}`, code ?? 1));

    await waitForApp(next, 180_000);
    if (syllabiEmpty) await syncSyllabi(appEnv.CRON_SECRET!);
    printBanner(appEnv.E2E_TEST_SECRET!);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    await shutdown("startup failed", 1);
  }
}

void main();
